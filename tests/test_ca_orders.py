"""
`tools/ca_orders.py` — the driver that turns HAA_G12's decision into Canadian orders.

Everything here is offline. The driver's three fetchers (signal, quotes, FX) are arguments of
`main`, and the tests that exercise the refusal paths pass fetchers that RAISE: a refusal that
happened after a download would pass a test that merely checked the exit code, and would
still have spent a network round-trip on a config it was always going to reject.

Anchors, in the sense of `tests/test_anchors.py`:

* the Yahoo symbols are the ones probed against Yahoo on 2026-09-23, written as literals —
  including the fact that the three Cboe Canada funds answer only as `.NE`;
* the demonstration CSV is compared byte for byte with the committed file, which was produced
  once and reviewed, not regenerated by the test;
* the demonstration's own inputs are recorded public prices and rates, and its capital is
  fictional and says so.
"""
