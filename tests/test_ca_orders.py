def _frame(closes):
    """A yfinance-shaped frame: columns ('Close', symbol)."""
    df = pd.DataFrame(closes)
    df.index = pd.to_datetime(df.index)
    df.columns = pd.MultiIndex.from_product([['Close'], df.columns])
    return df


class TestQuotesAreCheckedNotTrusted(unittest.TestCase):

    def test_the_last_close_on_or_before_the_date_is_taken(self):
        frame = _frame({'ZSP.TO': {'2026-09-18': 118.0, '2026-09-21': 119.0,
                                   '2026-09-23': 999.0},
                        'CGL-C.TO': {'2026-09-18': 50.0, '2026-09-21': float('nan'),
                                     '2026-09-23': float('nan')}})
        quotes = co.fetch_quotes({'ZSP', 'CGL.C'}, '2026-09-22',
                                 download=lambda *a, **k: frame)
        self.assertEqual(quotes['ZSP'], (119.0, '2026-09-21'))
        self.assertEqual(quotes['CGL.C'], (50.0, '2026-09-18'))

    def test_a_symbol_yahoo_did_not_return_is_absent_not_zero(self):
        frame = _frame({'ZSP.TO': {'2026-09-21': 119.0}})
        quotes = co.fetch_quotes({'ZSP', 'ZCOM'}, '2026-09-22',
                                 download=lambda *a, **k: frame)
        self.assertNotIn('ZCOM', quotes)

    def test_a_missing_or_stale_required_quote_is_a_refusal(self):
        quotes = {'ZSP': (119.0, '2026-09-01')}
        _, problems, _ = co.check_quotes({'ZSP', 'CGL.C'}, set(), quotes, '2026-09-22')
        self.assertEqual(len(problems), 2)
        self.assertTrue(any('ZSP' in p and '21 days' in p for p in problems))
        self.assertTrue(any('CGL.C' in p and 'no quote' in p for p in problems))

    def test_a_missing_alternative_class_is_only_a_note(self):
        prices, problems, notes = co.check_quotes({'ZSP'}, {'ZSP.U'},
                                                  {'ZSP': (119.0, '2026-09-22')}, '2026-09-22')
        self.assertEqual(problems, [])
        self.assertEqual(prices, {'ZSP': 119.0})
        self.assertTrue(any('ZSP.U' in n for n in notes))

    def test_required_and_optional_tickers(self):
        req, opt = co.quote_tickers({'SPY': 1.0}, [])
        self.assertEqual((req, opt), ({'ZSP'}, {'ZSP.U'}))
        req, opt = co.quote_tickers({'BIL': 1.0},
                                    [{'ticker': 'ZSP', 'qty': 5, 'currency': 'CAD'}])
        self.assertEqual((req, opt), ({'UBIL.U', 'ZSP'}, set()))


SIGNAL = co.Signal({'SPY': 0.5, 'GLD': 0.5}, '2026-08-31', {'TIP': 0.01}, None,
                   {'source': 'test'})
FRESH = {'ZSP': (100.0, '2026-09-22'), 'ZSP.U': (100.0 / 1.4, '2026-09-22'),
         'CGL.C': (50.0, '2026-09-22')}


class TestTheDriver(unittest.TestCase):

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def _main(self, raw, *argv, signal=SIGNAL, quotes=FRESH):
        path = _write(self.tmp.name, raw)
        return _quiet(co.main, ['--config', path, '--no-journal', *argv],
                      fetch_signal=lambda: signal,
                      fetch_quotes_fn=lambda tickers, day: dict(quotes),
                      fx_resolver=lambda manual=None: RATE)

    def test_a_missing_config_refuses_before_any_fetch(self):
        rc, out = _quiet(co.main, ['--config', os.path.join(self.tmp.name, 'none.json')],
                         fetch_signal=_boom, fetch_quotes_fn=_boom, fx_resolver=_boom)
        self.assertEqual(rc, 1)
        self.assertIn('does not exist', out)

    def test_refused_leverage_refuses_before_any_fetch(self):
        path = _write(self.tmp.name, _config(execution={'leverage': 1.3}))
        rc, out = _quiet(co.main, ['--config', path], fetch_signal=_boom,
                         fetch_quotes_fn=_boom, fx_resolver=_boom)
        self.assertEqual(rc, 1)
        self.assertIn('EXEC-001', out)

    def test_hand_computed_orders(self):
        """100,000 CAD, 50/50, at 100.00 and 50.00: 500 ZSP and 1,000 CGL.C."""
        rc, out = self._main(_config())
        self.assertEqual(rc, 0, out)
        self.assertRegex(out, r'BUY\s+500\s+ZSP\s')
        self.assertRegex(out, r'BUY\s+1,000\s+CGL\.C\s')
        # The weights line names SPY and GLD, as it should; no ORDER line may.
        traded = [line.split()[2] for line in out.splitlines()
                  if line.split()[:1] in (['BUY'], ['SELL'])]
        self.assertEqual(sorted(traded), ['CGL.C', 'ZSP'])
        cam.assert_no_us_tickers(traded)

    def test_a_stale_quote_refuses(self):
        stale = dict(FRESH, ZSP=(100.0, '2026-08-01'))
        rc, out = self._main(_config(), quotes=stale)
        self.assertEqual(rc, 1)
        self.assertIn('too old', out)

    def test_a_typed_price_wins_over_the_download(self):
        rc, out = self._main(_config(prices={'ZSP': 200.0}))
        self.assertEqual(rc, 0, out)
        self.assertRegex(out, r'BUY\s+250\s+ZSP\s')

    def test_a_stale_signal_is_printed_first(self):
        signal = SIGNAL._replace(stale_note='SIGNAL IS 2 MONTHS OLD')
        rc, out = self._main(_config(), signal=signal)
        self.assertEqual(rc, 0)
        self.assertLess(out.index('SIGNAL IS 2 MONTHS OLD'), out.index('BUY'))

    def test_the_journal_is_written_under_logs_and_every_row_names_its_signal(self):
        cfg = co.parse_config(_config())
        result = co.build(cfg, SIGNAL, {'ZSP': 100.0, 'CGL.C': 50.0}, RATE)
        jpath, cpath = co.journal(result, SIGNAL, FRESH, [], directory=self.tmp.name)
        with open(cpath, encoding='utf-8') as fh:
            rows = list(__import__('csv').DictReader(fh))
        self.assertTrue(rows)
        self.assertEqual({r['signal_date'] for r in rows}, {'2026-08-31'})
        with open(jpath, encoding='utf-8') as fh:
            self.assertEqual(json.load(fh)['signal']['signal_date'], '2026-08-31')

    def test_the_default_journal_and_config_are_outside_git(self):
        self.assertEqual(os.path.commonpath([co.JOURNAL_DIR, os.path.join(ROOT, 'logs')]),
                         os.path.join(ROOT, 'logs'))
        with open(os.path.join(ROOT, '.gitignore'), encoding='utf-8') as fh:
            ignored = {line.strip() for line in fh}
        self.assertIn('logs/', ignored)
        self.assertIn('ca_execution.json', ignored)
        self.assertNotIn('ca_execution.example.json', ignored)


class TestTheDemonstration(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.results, cls.csv_text = co.run_demo()
        with open(co.DEMO_INPUT, encoding='utf-8') as fh:
            cls.demo = json.load(fh)

    def test_it_reproduces_the_committed_csv_byte_for_byte(self):
        with open(co.DEMO_CSV, encoding='utf-8', newline='') as fh:
            self.assertEqual(self.csv_text, fh.read())

    def test_the_capital_is_declared_fictional(self):
        self.assertIn('FICTIONAL', self.demo['_comment'])
        self.assertEqual(self.demo['cash'], {'CAD': 100000.0, 'USD': 0.0})

    def test_every_row_names_one_of_the_demonstrated_signals(self):
        months = {m['signal_date'] for m in self.demo['months']}
        rows = list(__import__('csv').DictReader(io.StringIO(self.csv_text)))
        self.assertEqual({r['signal_date'] for r in rows}, months)

    def test_no_us_ticker_reaches_the_demonstration(self):
        rows = list(__import__('csv').DictReader(io.StringIO(self.csv_text)))
        traded = [r['exec_ticker'] for r in rows if r['side'] != 'CONVERT']
        cam.assert_no_us_tickers(traded)

    def test_the_second_month_is_a_full_rotation_into_the_defensive_sleeve(self):
        """August 2026: TIP's 13612U is negative, the canary is dead, HAA_G12 is 100% BIL —
        so every July holding is sold, CAD is converted, and UBIL.U is bought."""
        signal, result = self.results[1]
        self.assertLess(signal.canary['TIP'], 0)
        self.assertEqual(signal.weights, {'BIL': 1.0})
        sides = [(o['side'], o['ticker']) for o in result['orders']]
        self.assertEqual(sorted(t for s, t in sides if s == 'SELL'),
                         sorted(o['ticker'] for o in self.results[0][1]['orders']))
        self.assertEqual([t for s, t in sides if s == 'BUY'], ['UBIL.U'])
        self.assertEqual([f['direction'] for f in result['fx_orders']], ['CAD->USD'])


