def _boom(*_a, **_k):
    raise AssertionError('a fetcher was called; this path must refuse before any network')


def _config(**over):
    raw = {'cash': {'CAD': 100_000.0, 'USD': 0.0}, 'positions': [],
           'execution': {'prefer_usd_units': False}}
    raw.update(over)
    return raw


def _write(tmp, raw):
    path = os.path.join(tmp, 'ca_execution.json')
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(raw, fh)
    return path


def _quiet(fn, *a, **k):
    buf = io.StringIO()
    with redirect_stdout(buf):
        rc = fn(*a, **k)
    return rc, buf.getvalue()


class TestTheConfigIsStrict(unittest.TestCase):

    def test_a_missing_file_points_at_the_template(self):
        with self.assertRaises(co.ConfigError) as ctx:
            co.load_config(os.path.join(ROOT, 'no-such-dir', 'ca_execution.json'))
        self.assertIn('ca_execution.example.json', str(ctx.exception))
        self.assertIn('gitignored', str(ctx.exception))

    def test_the_committed_template_parses(self):
        cfg = co.load_config(co.EXAMPLE_PATH)
        self.assertEqual(cfg['exec_config'].leverage, 1.0)
        cam.assert_no_us_tickers([p['ticker'] for p in cfg['positions']])

    def test_a_misspelt_key_is_refused_rather_than_ignored(self):
        """`positons` ignored would be a book with no holdings, bought a second time."""
        with self.assertRaises(co.ConfigError) as ctx:
            co.parse_config(_config(positons=[{'ticker': 'ZSP', 'qty': 1}]))
        self.assertIn('positons', str(ctx.exception))

    def test_a_us_ticker_among_the_holdings_is_refused(self):
        with self.assertRaises(ValueError) as ctx:
            co.parse_config(_config(positions=[{'ticker': 'SPY', 'qty': 10}]))
        self.assertIn('SPY', str(ctx.exception))

    def test_a_stated_currency_must_match_the_table(self):
        with self.assertRaises(co.ConfigError):
            co.parse_config(_config(positions=[{'ticker': 'ZSP.U', 'qty': 10,
                                                'currency': 'CAD'}]))

    def test_the_currency_is_read_off_the_table_when_not_stated(self):
        cfg = co.parse_config(_config(positions=[{'ticker': 'UBIL.U', 'qty': 3}]))
        self.assertEqual(cfg['positions'][0]['currency'], 'USD')

    def test_negative_cash_and_non_numbers_are_refused(self):
        for raw in (_config(cash={'CAD': -1.0}), _config(cash={'CAD': True}),
                    _config(cash={'EUR': 1.0}),
                    _config(positions=[{'ticker': 'ZSP', 'qty': 0}]),
                    _config(positions=[{'ticker': 'ZSP', 'qty': 'ten'}])):
            with self.subTest(raw=raw), self.assertRaises(co.ConfigError):
                co.parse_config(raw)

    def test_leverage_above_one_is_refused(self):
        with self.assertRaises(CAExecutionError) as ctx:
            co.parse_config(_config(execution={'leverage': 1.3}))
        self.assertIn('EXEC-001', str(ctx.exception))

    def test_an_unknown_execution_setting_is_refused(self):
        with self.assertRaises(co.ConfigError):
            co.parse_config(_config(execution={'leverage_factor': 1.0}))


